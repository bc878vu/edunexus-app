// Syntax highlighting + copy support for article code blocks.
//
// Used by BOTH article renderers (the SPA ArticlesPage and the standalone
// SSR article page) so code looks the same everywhere: VS Code Dark+
// inspired colours, applied automatically — the author writes plain code,
// the reader sees coloured code. No author action, no stored markup.
//
// Pipeline: sanitize first (article-sanitize.mjs), THEN highlight. The
// highlighter only touches <pre>...</pre> segments of already-sanitized
// HTML, so prose is never coloured and its own output is never
// re-sanitized (the <span class="tok-…"> and copy <button> it emits are
// generated by this trusted code, and the code text itself is escaped).

const KEYWORDS = new Set([
  // SQL
  'select', 'from', 'where', 'join', 'inner', 'left', 'right', 'full',
  'outer', 'cross', 'on', 'group', 'by', 'order', 'asc', 'desc', 'as',
  'and', 'or', 'not', 'null', 'is', 'in', 'like', 'between', 'exists',
  'distinct', 'union', 'all', 'insert', 'into', 'values', 'update',
  'delete', 'create', 'table', 'drop', 'alter', 'index', 'sum', 'count',
  'avg', 'min', 'max', 'case', 'when', 'then', 'else', 'end',
  // Common general-purpose keywords (JS / Python / C-like)
  'function', 'return', 'if', 'elif', 'for', 'while', 'def', 'class',
  'import', 'from', 'print', 'const', 'let', 'var', 'true', 'false',
]);

const ESCAPES = { '&': '&amp;', '<': '&lt;', '>': '&gt;' };
function escapeHtml(s) {
  return String(s).replace(/[&<>]/g, (c) => ESCAPES[c]);
}

function decodeEntities(s) {
  return String(s)
    .replace(/&nbsp;/g, ' ')
    .replace(/&lt;/g, '<')
    .replace(/&gt;/g, '>')
    .replace(/&quot;/g, '"')
    .replace(/&#39;/g, "'")
    .replace(/&amp;/g, '&');
}

// Tokenize raw code text into coloured HTML. Single pass, no regex
// backtracking over the whole block: strings and comments are consumed
// greedily so keywords inside them are never coloured.
export function highlightCodeText(raw) {
  const text = String(raw ?? '');
  let out = '';
  let i = 0;
  const n = text.length;
  const isIdentStart = (c) => /[A-Za-z_]/.test(c);
  const isIdent = (c) => /[A-Za-z0-9_]/.test(c);
  while (i < n) {
    const c = text[i];
    const next = text[i + 1] || '';
    // Line comments: -- (SQL), // and # (general)
    if ((c === '-' && next === '-') || (c === '/' && next === '/') || c === '#') {
      let j = i;
      while (j < n && text[j] !== '\n') j++;
      out += '<span class="tok-com">' + escapeHtml(text.slice(i, j)) + '</span>';
      i = j;
      continue;
    }
    // Block comments: /* ... */
    if (c === '/' && next === '*') {
      const end = text.indexOf('*/', i + 2);
      const j = end === -1 ? n : end + 2;
      out += '<span class="tok-com">' + escapeHtml(text.slice(i, j)) + '</span>';
      i = j;
      continue;
    }
    // Strings: '...' and "..." — backslash escapes, plus SQL '' escapes.
    if (c === "'" || c === '"') {
      const quote = c;
      let j = i + 1;
      while (j < n) {
        if (text[j] === '\\' && j + 1 < n) { j += 2; continue; }
        if (text[j] === quote) {
          // SQL doubled-quote escape: '' inside a '...' string.
          if (quote === "'" && text[j + 1] === "'") { j += 2; continue; }
          j++;
          break;
        }
        j++;
      }
      out += '<span class="tok-str">' + escapeHtml(text.slice(i, j)) + '</span>';
      i = j;
      continue;
    }
    // Numbers: 123, 3.14 (not part of an identifier).
    if (/\d/.test(c) && (i === 0 || !isIdent(text[i - 1]))) {
      let j = i;
      while (j < n && /\d/.test(text[j])) j++;
      if (text[j] === '.' && /\d/.test(text[j + 1] || '')) {
        j++;
        while (j < n && /\d/.test(text[j])) j++;
      }
      out += '<span class="tok-num">' + escapeHtml(text.slice(i, j)) + '</span>';
      i = j;
      continue;
    }
    // Identifiers: keywords, function calls (name followed by '('), else plain.
    if (isIdentStart(c)) {
      let j = i;
      while (j < n && isIdent(text[j])) j++;
      const word = text.slice(i, j);
      if (KEYWORDS.has(word.toLowerCase())) {
        out += '<span class="tok-kw">' + escapeHtml(word) + '</span>';
      } else {
        let k = j;
        while (k < n && (text[k] === ' ' || text[k] === '\t')) k++;
        if (text[k] === '(') {
          out += '<span class="tok-fn">' + escapeHtml(word) + '</span>';
        } else {
          out += escapeHtml(word);
        }
      }
      i = j;
      continue;
    }
    out += escapeHtml(c);
    i++;
  }
  return out;
}

// Highlight every <pre> block in sanitized article HTML and wrap it with
// a Copy button. Prose outside <pre> is left byte-identical. A <pre>
// that wraps a single <code> element (a common authoring pattern) is
// unwrapped before tokenizing so the code itself is coloured.
export function highlightArticleCode(html) {
  return String(html ?? '').replace(/<pre>([\s\S]*?)<\/pre>/g, (m, inner) => {
    const codeMatch = /^<code>([\s\S]*)<\/code>$/.exec(inner);
    const raw = decodeEntities(codeMatch ? codeMatch[1] : inner);
    return (
      '<div class="edx-code-wrap"><pre>' +
      highlightCodeText(raw) +
      '</pre><button type="button" class="edx-code-copy">📋 Copy</button></div>'
    );
  });
}

// Wrap every <table> in a horizontal-scroll container. This is what
// makes tables responsive: the table keeps its natural column widths
// (headers never squeeze mid-word) and scrolls inside its container
// when it is wider than the screen. Applied at render time, so every
// article's tables — past and future — get it with no re-save. Runs on
// already-sanitized HTML, which never contains edx-table-wrap, so a
// table is wrapped exactly once.
export function wrapArticleTables(html) {
  return String(html ?? '').replace(/<table[\s\S]*?<\/table>/g, (m) => {
    return '<div class="edx-table-wrap">' + m + '</div>';
  });
}

// --- Urdu/Arabic articles (added 2026-11-01) ----------------------------
// Render-time RTL + Quran-verse presentation, mirroring the code-block
// standard: no stored content is changed (the article body in the
// database is never touched), so every past and future article gets it
// automatically, and English articles are unaffected.
//
// RTL detection: the body is treated as Urdu/Arabic only when
// Arabic-script letters dominate Latin letters by a wide margin, so an
// English article that merely quotes one Arabic word stays LTR.
// Verse detection: a paragraph (or a <br>-separated line inside one) is
// a Quran verse when it carries a Quranic stop mark (ۖ ۗ ۘ ۙ ۚ ۛ ۜ) or
// when it is long, almost entirely Arabic-script, heavily vocalised and
// free of Urdu-specific letters (ٹ ڈ ڑ ں ھ ی ک ے). Urdu prose always
// contains those letters (کی، کے، میں، ہے، ...), so prose is never
// mistaken for a verse. A verse block only re-wraps text — it never
// drops, reorders or rewords a character — and its Copy button copies
// the verse text exactly.
const ARABIC_LETTER_RE = /[\u0600-\u06FF\u0750-\u077F\u08A0-\u08FF\uFB50-\uFDFF\uFE70-\uFEFF]/g;
const LATIN_LETTER_RE = /[A-Za-z]/g;
const URDU_SPECIFIC_RE = /[\u0679\u0688\u0691\u06BA\u06BE\u06CC\u06A9\u06D2]/g;
const QURAN_STOP_RE = /[\u06D6-\u06DC]/;
const DIACRITIC_RE = /[\u064B-\u0652\u0670]/g;

function stripEnhanceTags(s) {
  return String(s ?? '').replace(/<[^>]*>/g, ' ');
}

function isQuranVerseText(segment) {
  const t = stripEnhanceTags(segment).trim();
  if (!t) return false;
  if (QURAN_STOP_RE.test(t)) return true;
  const arabic = (t.match(ARABIC_LETTER_RE) || []).length;
  const latin = (t.match(LATIN_LETTER_RE) || []).length;
  if (arabic < 20 || latin > arabic * 0.1) return false;
  const diacritics = (t.match(DIACRITIC_RE) || []).length;
  const urduSpecific = (t.match(URDU_SPECIFIC_RE) || []).length;
  return diacritics >= 5 && urduSpecific === 0;
}

function isRtlBody(html) {
  const text = stripEnhanceTags(html);
  const arabic = (text.match(ARABIC_LETTER_RE) || []).length;
  const latin = (text.match(LATIN_LETTER_RE) || []).length;
  return arabic > 100 && arabic > latin * 2;
}

function verseWrap(innerHtml) {
  return (
    '<div class="edx-verse-wrap" dir="rtl" lang="ar"><div class="edx-verse-text">' +
    innerHtml +
    '</div><button type="button" class="edx-verse-copy">📋 Copy</button></div>'
  );
}

// Re-wrap Quran-verse paragraphs (or verse lines inside a paragraph)
// as verse blocks. Non-verse segments are regrouped into <p> blocks
// with their original <br> separators, so no text is lost or moved.
export function enhanceRtlAndVerses(html) {
  let s = String(html ?? '');
  s = s.replace(/<p>([\s\S]*?)<\/p>/g, (m, inner) => {
    const segments = inner.split(/<br\s*\/?>/i);
    if (segments.length === 1) {
      return isQuranVerseText(inner) ? verseWrap(inner) : m;
    }
    let out = '';
    let buf = [];
    const flush = () => {
      if (buf.length) {
        out += '<p>' + buf.join('<br>') + '</p>';
        buf = [];
      }
    };
    for (const seg of segments) {
      if (isQuranVerseText(seg)) {
        flush();
        out += verseWrap(seg);
      } else {
        buf.push(seg);
      }
    }
    flush();
    return out;
  });
  if (isRtlBody(s)) {
    s = '<div class="edx-rtl-body" dir="rtl" lang="ur">' + s + '</div>';
  }
  return s;
}

// Full render-time enhancement for an article body: syntax-coloured
// code blocks with Copy buttons, plus scrollable table wrappers,
// plus RTL + Quran-verse presentation for Urdu/Arabic articles.
export function enhanceArticleBodyHtml(html) {
  return enhanceRtlAndVerses(wrapArticleTables(highlightArticleCode(html)));
}
// Attach to a container (React onClick) or to document (SSR inline
// script uses its own copy of this logic). Safe to call for any click:
// it no-ops unless the click landed on a .edx-code-copy or
// .edx-verse-copy button. A verse button copies its verse text, a code
// button copies its <pre> text — same feedback, same fallback.
export function handleCodeCopyClick(e) {
  const target = e && e.target;
  const btn = target && target.closest ? target.closest('.edx-code-copy,.edx-verse-copy') : null;
  if (!btn) return;
  const wrap = btn.closest('.edx-code-wrap,.edx-verse-wrap');
  const src = wrap && (wrap.querySelector('pre') || wrap.querySelector('.edx-verse-text'));
  if (!src) return;
  const text = src.textContent || '';
  const done = () => {
    const old = btn.textContent;
    btn.textContent = 'Copied ✓';
    setTimeout(() => { btn.textContent = old; }, 2000);
  };
  if (typeof navigator !== 'undefined' && navigator.clipboard && navigator.clipboard.writeText) {
    navigator.clipboard.writeText(text).then(done).catch(() => fallbackCopy(text, done));
  } else {
    fallbackCopy(text, done);
  }
}

function fallbackCopy(text, done) {
  try {
    const ta = document.createElement('textarea');
    ta.value = text;
    ta.style.cssText = 'position:fixed;opacity:0';
    document.body.appendChild(ta);
    ta.select();
    document.execCommand('copy');
    document.body.removeChild(ta);
    done();
  } catch (err) {
    // Clipboard unavailable; leave the button unchanged.
  }
}
